function K = shm_nonideal_conditions()
%SHM_NONIDEAL_CONDITIONS The non-ideal switching conditions of Table 4.
%   K = SHM_NONIDEAL_CONDITIONS() returns one element per condition, each
%   adding one effect to the previous: ideal switches, datasheet conduction
%   drops, dead time, neutral-point offset with capacitance mismatch, timer
%   resolution, and all combined. Fields: name, tag, drops, td (s), eps_dc
%   (fraction of Vdc/2), Cmis, tq (s).

K = struct( ...
    'name',   {'ideal switches', 'datasheet devices', '+ dead time 2 $\mu$s', '+ NP offset 2\,\%', ...
               '+ timer 1 $\mu$s', 'all combined'}, ...
    'tag',    {'ideal', 'drops', 'dt', 'np', 'tq', 'all'}, ...
    'drops',  {false, true, true, true, true, true}, ...
    'td',     {0, 0, 2e-6, 0, 0, 2e-6}, ...
    'eps_dc', {0, 0, 0, 0.02, 0, 0.02}, ...
    'Cmis',   {0, 0, 0, 0.10, 0, 0.10}, ...
    'tq',     {0, 0, 0, 0, 1e-6, 1e-6});
end
