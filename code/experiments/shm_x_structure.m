function E = shm_x_structure(D)
%SHM_X_STRUCTURE Stage E1: multiplicity of optima and structure of the branches.
%   E = SHM_X_STRUCTURE(D)
%     E.anchors   per anchor: distinct optima, THD spread, share of starts
%                 reaching the best, singletons, Chao1 estimate
%     E.branches  per branch: range, end types, smoothness, owned share,
%                 effective angles, THD49

S = D.seeds;
ha = {'Ma','random_starts','converged','distinct_optima','best_THD49_pct', ...
      'median_distinct_THD49_pct','worst_distinct_THD49_pct','starts_reaching_best_pct', ...
      'distinct_at_0p5deg','distinct_at_2deg','distinct_THD_levels','optima_within_1pp_of_best', ...
      'found_once_pct','chao1_estimate'};
ra = cell(numel(S), numel(ha));
rob = nan(numel(S), 6);
for a = 1:numel(S)
    if isempty(S(a).thd)
        ra(a, :) = {S(a).Ma, S(a).nstart, S(a).nok, 0, NaN, NaN, NaN, 0, 0, 0, 0, 0, NaN, NaN};
        continue
    end
    lev = 1 + sum(diff(sort(S(a).thd)) > 1e-5);
    f1 = sum(S(a).count == 1);  f2 = sum(S(a).count == 2);  n = max(S(a).nok, 1);
    chao = numel(S(a).thd) + (n - 1) / n * f1 * (f1 - 1) / (2 * (f2 + 1));
    rob(a, :) = [recluster(S(a).X, 0.5), recluster(S(a).X, 2), lev, sum(S(a).thd - S(a).thd(1) <= 0.01), ...
                 100 * f1 / numel(S(a).thd), chao];
    ra(a, :) = {S(a).Ma, S(a).nstart, S(a).nok, numel(S(a).thd), 100*S(a).thd(1), ...
                100*median(S(a).thd), 100*max(S(a).thd), 100*S(a).count(1)/max(S(a).nok, 1), ...
                rob(a, 1), rob(a, 2), rob(a, 3), rob(a, 4), rob(a, 5), rob(a, 6)};
end

B = D.branch;
hb = {'branch','Ma_from','Ma_to','ends','grid_points','owned_pct','stored','median_step_deg', ...
      'max_step_deg','collapsed_pairs','effective_angles','mean_theta1_deg','mean_thetaN_deg', ...
      'min_THD49_pct','mean_THD49_pct'};
rb = cell(numel(B), numel(hb));
for k = 1:numel(B)
    rb(k, :) = {k, B(k).Ma_lo, B(k).Ma_hi, B(k).ends, B(k).n, 100*B(k).owned, ...
                double(any(D.sel == k)), B(k).median_step_deg, B(k).max_step_deg, ...
                B(k).collapsed_pairs, B(k).effective_angles, B(k).theta1_deg, B(k).thetaN_deg, ...
                B(k).thd_min, B(k).thd_mean};
end
own = cell2mat(rb(:, 6));
[~, o] = sort(own, 'descend');
rb = rb(o, :);

st = D.stats;
v = all(isfinite(rob), 2);
st.distinct_mean_0p5deg = mean(rob(v, 1));
st.distinct_mean_2deg   = mean(rob(v, 2));
st.thd_levels_mean      = mean(rob(v, 3));
st.within_1pp_mean      = mean(rob(v, 4));
st.found_once_pct_mean  = mean(rob(v, 5));
st.chao1_mean           = mean(rob(v, 6));
tol = 0.05;
if isfield(D.opts, 'seed') && isfield(D.opts.seed, 'TOL_DEG'), tol = D.opts.seed.TOL_DEG; end
npr = 0;  if isfield(st, 'n_probe_traces'), npr = st.n_probe_traces; end
nfo = 0;  if isfield(st, 'n_fold_traces'),  nfo = st.n_fold_traces;  end
E.anchors  = struct('name', 'E1a_multiplicity', 'header', {ha}, 'data', {ra}, ...
    'note', sprintf(['Multistart at each anchor (fmincon SQP from uniformly random feasible angle ' ...
    'sets). Distinct optima are clustered at %.2f deg in every angle. On average %.1f distinct ' ...
    'local optima per anchor (max %d); the best one is reached by %.1f%% of converged starts. ' ...
    'Clustered at 0.5 deg: %.1f; at 2 deg: %.1f; distinct THD49 levels (1e-3 pp apart): %.1f; ' ...
    'within 1 pp of the best: %.1f. %.0f%% of the distinct optima were reached by one start only, so ' ...
    'the counts are lower bounds; the Chao1 estimate of the total is %.0f per anchor.'], ...
    tol, st.mean_distinct, st.max_distinct, 100*st.best_hit_rate, ...
    st.distinct_mean_0p5deg, st.distinct_mean_2deg, st.thd_levels_mean, st.within_1pp_mean, ...
    st.found_once_pct_mean, st.chao1_mean));
E.branches = struct('name', 'E1b_branches', 'header', {hb}, 'data', {rb}, ...
    'note', sprintf(['%d continuous branches traced by warm-started continuation (%d traces, %d of them ' ...
    'from the probe multistart and %d from the fold-end search, merged). %d branches own part of the ' ...
    'per-Ma optimum; the owner changes ' ...
    '%d times across the grid, and the optimal angle vector jumps by %.1f deg on average at those ' ...
    'changes (%.1f deg at worst). A stored subset of %d branches reproduces the envelope to %.4f pp ' ...
    'mean, %.4f pp worst.'], ...
    st.n_branches, st.n_traces, npr, nfo, st.n_owners, st.owner_changes, st.env_step_at_change_mean_deg, ...
    st.env_step_max_deg, st.n_stored, st.stored_gap_mean_pp, st.stored_gap_max_pp));
own = D.own(:);  P = D.P;  gr = D.grid(:);
ch = find(own(1:end-1) ~= own(2:end) & isfinite(own(1:end-1)) & isfinite(own(2:end)));
hc = {'Ma_from','Ma_to','branch_from','branch_to','largest_angle_move_deg','waveform_differs_pct', ...
      'THD49_from_pct','THD49_to_pct','stay_cost_pp','stay_cost_4steps_pp'};
rc = nan(numel(ch), numel(hc));
for q = 1:numel(ch)
    g = ch(q);  k1 = own(g);  k2 = own(g + 1);
    c1 = 100 * (D.THD(g + 1, k1) - D.env(g + 1));
    c4 = NaN;  if g + 4 <= numel(gr), c4 = 100 * (D.THD(g + 4, k1) - D.env(g + 4)); end
    rc(q, :) = [gr(g), gr(g + 1), k1, k2, max(abs(D.envTH(g + 1, :) - D.envTH(g, :))) * 180/pi, ...
                shm_wavediff(D.envTH(g, :), D.envTH(g + 1, :), P.s), 100 * D.env(g), 100 * D.env(g + 1), c1, c4];
end
if ~isempty(rc)
    st.jump_wave_mean = mean(rc(:, 6));  st.jump_wave_max = max(rc(:, 6));  st.jump_wave_min = min(rc(:, 6));
    [~, q] = max(rc(:, 5));  st.jump_wave_at_maxangle = rc(q, 6);  st.jump_maxangle_at_change = rc(q, 5);
end
E.changes = struct('name', 'E1c_owner_changes', 'header', {hc}, 'data', rc, 'note', ['Every owner change ' ...
    'of the per-Ma optimum. largest_angle_move: the largest move of one sorted angle (what a table ' ...
    'interpolates across). waveform_differs: share of the period in which the two optimal voltages ' ...
    'differ. stay_cost: THD49 of staying on the old branch minus the optimum, one and four grid steps ' ...
    'after the change (NaN: the old branch ends).']);
E.stats = st;
end

function n = recluster(X, tol_deg)
tol = tol_deg * pi/180;
rep = zeros(0, size(X, 2));
for i = 1:size(X, 1)
    if ~isempty(rep) && min(max(abs(rep - repmat(X(i, :), size(rep, 1), 1)), [], 2)) <= tol
        continue
    end
    rep(end+1, :) = X(i, :); %#ok<AGROW>
end
n = size(rep, 1);
end
